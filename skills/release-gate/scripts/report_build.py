#!/usr/bin/env python3
"""Build the release-gate report (Markdown, self-contained HTML, SARIF, JSON).

Reads everything from <project>/.release-gate/:
  findings.json         list of finding/check entries (finding.schema.json),
                        or {"entries": [...]}; extra files via --findings
  config.yaml           intake answers (config.schema.json)
  waivers.yaml          accepted risks (waivers.schema.json)
  data-inventory.yaml   privacy source of truth
  privacy.json          optional: regimes, rights tests, cookie audit
  documents.json        optional: generated documents + lawyer questions
  perf.json             optional: load-test results
  history/*.json        previous run summaries (for trend)

Writes reports/release-gate-<date>.{md,html,sarif,json} and history/<stamp>.json,
then runs report_lint. If lint fails the files are written as
release-gate-<date>.lint-failed.* and the exit code is 2, so a failing report
can never be mistaken for a final one.

Verdict rules (spec 13.1, with two deliberate tightenings marked *):
  BLOCK  - any open critical without an active waiver
         - any open high without an active waiver
         - * any EXPLOITED critical/high, waived or not (a proven hole is not
           an accepted risk)
         - * full mode only: half or more of the critical checks this mode is
           expected to run are NOT-TESTED for reasons other than "skipped by
           user" (the gate fails closed when it could not look)
  SHIP WITH ACCEPTED RISKS
         - any applicable critical-category check that is not VERIFIED-ABSENT,
           or VERIFIED-ABSENT but not upheld by adversarial verification
         - any active waiver, any open medium finding, or a mode other than full
  SHIP   - none of the above
"""
from __future__ import annotations

import argparse
import html
import json
import re
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import rglib  # noqa: E402

CATALOG_FILE = rglib.SKILL_DIR / "references" / "checks.yaml"
MODES = ("quick", "full", "legal", "retest")
STALE_DAYS = 365
CLASS_STRENGTH = {"EXPLOITED": 3, "TOOL-CONFIRMED": 2, "SUSPECTED": 1}
OPEN_STATUSES = ("open", "fix-proposed")

LIMITATIONS = [
    "This is not a substitute for a professional penetration test or for a lawyer.",
    "Automated scanning misses business-logic flaws; the manual-review items are only as good as the code paths that were read.",
    "Load tests on local hardware do not predict production capacity exactly.",
    "A scanner that reports nothing has only shown that this scanner, with its rules and scope, found nothing.",
    "Automated accessibility tools catch only part of WCAG issues; manual checks are still needed.",
    "Legal documents are drafts generated from the data inventory, not legal advice.",
]

DISCLAIMER = (
    "This report was generated by release-gate, an automated tool, and is provided as is, without warranty of any kind. "
    "It is not legal advice, not a penetration test, and not a certification of compliance. A SHIP verdict does not "
    "guarantee the absence of vulnerabilities, bugs or legal risk; it states only what was checked and how, as listed "
    "in the coverage matrix. The decision to release, and responsibility for it, remain with the publisher. "
    "See DISCLAIMER.md in the release-gate repository."
)


# --------------------------------------------------------------------------- loading

def _entries_from(data: Any) -> list[dict]:
    if data is None:
        return []
    if isinstance(data, dict):
        return list(data.get("entries", []))
    return list(data)


def load_state(project: Path, extra_findings: list[Path]) -> dict:
    sd = rglib.state_dir(project)
    entries = _entries_from(rglib.load_data(sd / "findings.json"))
    for p in extra_findings:
        entries += _entries_from(rglib.load_data(p))
    history = []
    for hp in sorted((sd / "history").glob("*.json")):
        try:
            history.append(rglib.load_data(hp))
        except (json.JSONDecodeError, OSError):
            continue
    return {
        "state_dir": sd,
        "entries": entries,
        "config": rglib.load_data(sd / "config.yaml", {}) or {},
        "scope": rglib.load_data(sd / "scope.yaml", {}) or {},
        "waivers": (rglib.load_data(sd / "waivers.yaml", {}) or {}).get("waivers", []),
        "inventory": rglib.load_data(sd / "data-inventory.yaml", {}) or {},
        "privacy": rglib.load_data(sd / "privacy.json", {}) or {},
        "documents": rglib.load_data(sd / "documents.json", {}) or {},
        "perf": rglib.load_data(sd / "perf.json", {}) or {},
        "history": history,
    }


def load_catalog(path: Path = CATALOG_FILE) -> list[dict]:
    return rglib.load_data(path, {"checks": []})["checks"]


# --------------------------------------------------------------------------- applicability

def _surface(config: dict) -> dict:
    surf = dict(config.get("surface") or {})
    dist = set((config.get("product") or {}).get("distribution") or [])
    if "has_server" not in surf and dist:
        surf["has_server"] = bool(dist & {"website", "saas", "api", "self-hosted"})
    if "has_web_ui" not in surf and dist:
        surf["has_web_ui"] = bool(dist & {"website", "saas", "browser-extension"})
    return surf


def applies(check: dict, config: dict) -> bool | None:
    """True / False, or None when config lacks the answer (treated as applicable)."""
    cond = check.get("applies_when")
    if not cond:
        return True
    surf = _surface(config)
    feats = config.get("features") or {}
    dist = set((config.get("product") or {}).get("distribution") or [])
    unknown = False
    for key, want in cond.items():
        if key.startswith("features."):
            have = feats.get(key.split(".", 1)[1])
        elif key == "distribution":
            have = bool(dist & set(want)) if dist else None
            want = True
        elif key in ("has_server", "has_web_ui"):
            have = surf.get(key)
        else:
            have = None
        if have is None:
            unknown = True
        elif bool(have) != bool(want):
            return False
    return None if unknown else True


# --------------------------------------------------------------------------- coverage

def build_coverage(entries: list[dict], catalog: list[dict], config: dict, mode: str) -> list[dict]:
    skipped_phases = set(config.get("phases_skipped") or [])
    by_check: dict[str, list[dict]] = {}
    for e in entries:
        if e.get("check_id"):
            by_check.setdefault(e["check_id"], []).append(e)
    rows = []
    for chk in catalog:
        row = {
            "id": chk["id"], "title": chk["title"], "phase": chk["phase"],
            "category": chk["category"], "critical": bool(chk.get("critical")),
            "expected_in_mode": mode in chk.get("modes", []),
            "applicable": True, "evidence_class": "NOT-TESTED", "result": "",
            "reason": "", "artifacts": [], "adversarial_upheld": False, "skipped_by_user": False,
        }
        got = by_check.get(chk["id"], [])
        app = applies(chk, config)
        if app is False and not got:
            row.update(applicable=False, evidence_class="N/A", result="not applicable",
                       reason="does not apply to this product (config)")
            rows.append(row)
            continue
        findings = [e for e in got if e.get("kind") == "finding" and e.get("status") != "false-positive"]
        checks = [e for e in got if e.get("kind") == "check"]
        for e in got:
            row["artifacts"] += [ev["path"] for ev in e.get("evidence", []) if ev.get("path")]
        if findings:
            best = max(findings, key=lambda f: CLASS_STRENGTH.get(f["evidence_class"], 0))
            row["evidence_class"] = best["evidence_class"]
            row["result"] = f"issue found ({len(findings)})"
            row["reason"] = ", ".join(sorted(f["id"] for f in findings))
        elif checks:
            nts = [c for c in checks if c["evidence_class"] == "NOT-TESTED"]
            vas = [c for c in checks if c["evidence_class"] == "VERIFIED-ABSENT"]
            if nts:
                row["evidence_class"] = "NOT-TESTED"
                row["result"] = "partial" if vas else "not tested"
                row["reason"] = "; ".join(c.get("not_tested_reason", "") for c in nts)
                row["skipped_by_user"] = all("skipped by user" in c.get("not_tested_reason", "") for c in nts)
            elif vas and len(vas) == len(checks):
                row["evidence_class"] = "VERIFIED-ABSENT"
                row["result"] = "no issue observed"
                row["reason"] = "; ".join(c["title"] for c in vas)
                row["adversarial_upheld"] = all((c.get("adversarial") or {}).get("outcome") == "upheld" for c in vas)
            else:
                row["evidence_class"] = "SUSPECTED"
                row["result"] = "unresolved"
                row["reason"] = "; ".join(c["title"] for c in checks)
        elif chk["phase"] in skipped_phases:
            row.update(reason="skipped by user", result="not tested", skipped_by_user=True)
        elif not row["expected_in_mode"]:
            row.update(reason=f"not part of {mode} mode", result="not tested")
        else:
            row.update(reason="no result recorded", result="not tested")
        rows.append(row)
    return rows


# --------------------------------------------------------------------------- waivers

def split_waivers(waivers: list[dict], on: Any = None) -> tuple[list[dict], list[dict]]:
    day = rglib.parse_date(on) if on else rglib.today()
    active, expired = [], []
    for w in waivers:
        (active if rglib.parse_date(w["expires"]) >= day else expired).append(w)
    return active, expired


def waiver_for(finding: dict, waivers: list[dict]) -> dict | None:
    for w in waivers:
        m = w.get("match", {})
        if m.get("finding_id") and m["finding_id"] == finding.get("id"):
            return w
        if m.get("fingerprint") and m["fingerprint"] == finding.get("fingerprint"):
            return w
    return None


# --------------------------------------------------------------------------- verdict

def compute_verdict(entries: list[dict], coverage: list[dict], active_waivers: list[dict], mode: str) -> dict:
    if mode == "legal":
        return {"verdict": "NOT-EVALUATED", "reasons": ["legal mode produces documents and a consistency check, not a release verdict"],
                "blocking": [], "caps": []}
    blocking, caps = [], []
    open_findings = [e for e in entries if e.get("kind") == "finding" and e.get("status", "open") in OPEN_STATUSES]
    waived_in_effect = []
    for f in open_findings:
        sev, cls = f.get("severity"), f.get("evidence_class")
        w = waiver_for(f, active_waivers)
        if cls == "EXPLOITED" and sev in ("critical", "high"):
            note = " (waiver ignored: exploited critical/high cannot be waived)" if w else ""
            blocking.append(f"{f['id']}: EXPLOITED {sev} — {f['title']}{note}")
        elif sev in ("critical", "high") and not w:
            blocking.append(f"{f['id']}: unwaived {sev} ({cls}) — {f['title']}")
        elif w:
            waived_in_effect.append(f"{f['id']} waived by {w['id']} until {w['expires']}")
        elif sev == "medium":
            caps.append(f"{f['id']}: open medium — {f['title']}")

    crit_rows = [r for r in coverage if r["critical"] and r["applicable"]]
    if mode == "full":
        expected = [r for r in crit_rows if r["expected_in_mode"]]
        blind = [r for r in expected if r["evidence_class"] == "NOT-TESTED" and not r["skipped_by_user"]]
        if expected and len(blind) * 2 >= len(expected):
            blocking.append(
                f"insufficient evidence: {len(blind)} of {len(expected)} critical checks NOT-TESTED "
                f"({', '.join(r['id'] for r in blind)}); the gate cannot vouch for this release")
    for r in crit_rows:
        if r["evidence_class"] == "VERIFIED-ABSENT":
            if not r["adversarial_upheld"]:
                caps.append(f"{r['id']}: VERIFIED-ABSENT but not yet upheld by adversarial verification")
        elif r["evidence_class"] in ("NOT-TESTED", "SUSPECTED"):
            caps.append(f"{r['id']}: {r['evidence_class']} ({r['reason'] or r['result']})")
        # EXPLOITED/TOOL-CONFIRMED rows already surface as findings
    caps += waived_in_effect
    if mode != "full":
        caps.append(f"{mode} mode does not run every phase; this is not a release decision")

    if blocking:
        verdict = "BLOCK"
    elif caps:
        verdict = "SHIP WITH ACCEPTED RISKS"
    else:
        verdict = "SHIP"
    return {"verdict": verdict, "blocking": blocking, "caps": caps,
            "reasons": blocking or caps or ["every applicable critical check is VERIFIED-ABSENT and upheld; no open critical/high/medium findings"]}


# --------------------------------------------------------------------------- trend

def _key(e: dict) -> str:
    return e.get("fingerprint") or e["id"]


def compute_trend(entries: list[dict], history: list[dict]) -> dict:
    current_open = {_key(e) for e in entries if e.get("kind") == "finding" and e.get("status", "open") in OPEN_STATUSES}
    if not history:
        return {"previous_run": None, "new": sorted(current_open), "fixed": [], "regressions": []}
    prev = history[-1]
    prev_open = {f["key"] for f in prev.get("findings", []) if f.get("open")}
    ever_fixed = set()
    for h in history:
        ever_fixed |= {f["key"] for f in h.get("findings", []) if not f.get("open")}
    ever_fixed -= prev_open
    return {
        "previous_run": prev.get("run_at"),
        "new": sorted(current_open - prev_open - ever_fixed),
        "fixed": sorted(prev_open - current_open),
        "regressions": sorted(current_open & ever_fixed),
    }


def history_summary(entries: list[dict], verdict: dict, mode: str) -> dict:
    return {
        "run_at": rglib.now_iso(), "mode": mode, "verdict": verdict["verdict"],
        "counts": _counts(entries),
        "findings": [
            {"key": _key(e), "id": e["id"], "severity": e.get("severity"), "evidence_class": e["evidence_class"],
             "open": e.get("status", "open") in OPEN_STATUSES}
            for e in entries if e.get("kind") == "finding"
        ],
    }


def _counts(entries: list[dict]) -> dict:
    out = {s: 0 for s in rglib.SEVERITIES}
    for e in entries:
        if e.get("kind") == "finding" and e.get("status", "open") in OPEN_STATUSES:
            out[e.get("severity", "info")] += 1
    return out


# --------------------------------------------------------------------------- context

def build_context(state: dict, catalog: list[dict], mode: str, date: str) -> dict:
    entries = [dict(e) for e in state["entries"]]
    for e in entries:  # defensive: reports never carry raw secrets
        for k in ("title", "impact", "repro", "fix", "not_tested_reason"):
            if isinstance(e.get(k), str):
                e[k] = rglib.redact_text(e[k])
    active, expired = split_waivers(state["waivers"])
    coverage = build_coverage(entries, catalog, state["config"], mode)
    verdict = compute_verdict(entries, coverage, active, mode)
    findings = sorted(
        [e for e in entries if e.get("kind") == "finding" and e.get("status") != "false-positive"],
        key=lambda f: (rglib.SEVERITY_RANK.get(f.get("severity"), 9), -CLASS_STRENGTH.get(f["evidence_class"], 0), f["id"]))
    false_pos = [e for e in entries if e.get("status") == "false-positive"]
    adversarial = [e for e in entries if (e.get("adversarial") or {}).get("required")]
    regimes = []
    for r in (state["privacy"].get("regimes") or []):
        r = dict(r)
        lv = r.get("last_verified")
        r["stale"] = bool(lv) and (rglib.today() - rglib.parse_date(lv)).days > STALE_DAYS
        regimes.append(r)
    product = (state["config"].get("product") or {}).get("name") or Path(state["state_dir"]).parent.name
    return {
        "product": product, "date": date, "mode": mode, "generated_at": rglib.now_iso(),
        "verdict": verdict, "coverage": coverage, "findings": findings, "false_positives": false_pos,
        "adversarial": adversarial, "counts": _counts(entries),
        "waivers_active": active, "waivers_expired": expired,
        "inventory": state["inventory"], "privacy": state["privacy"], "regimes": regimes,
        "documents": state["documents"], "perf": state["perf"],
        "trend": compute_trend(entries, state["history"]),
        "entries": entries, "config": state["config"],
    }


# --------------------------------------------------------------------------- markdown

def _md_cell(text: Any) -> str:
    return str(text if text is not None else "").replace("|", "\\|").replace("\n", " ")


def _ev_link(path: str) -> str:
    return f"[{_md_cell(path)}](../{path})"


def render_md(ctx: dict) -> str:
    v = ctx["verdict"]
    out = [f"# release-gate report: {ctx['product']}", "",
           f"Date: {ctx['date']} · Mode: `{ctx['mode']}` · Generated: {ctx['generated_at']}", "",
           f"## 1. Verdict: **{v['verdict']}**", ""]
    for r in v["reasons"]:
        out.append(f"- {_md_cell(r)}")
    c = ctx["counts"]
    out += ["", f"Open findings: {c['critical']} critical, {c['high']} high, {c['medium']} medium, {c['low']} low, {c['info']} info.", ""]

    out += ["## 2. Coverage matrix", "",
            "What was actually checked, and how strong the evidence is. NOT-TESTED means nobody looked; it is not a pass.", "",
            "| Check | Phase | Critical | Evidence class | Result | Detail | Artifact |",
            "|---|---|---|---|---|---|---|"]
    for r in ctx["coverage"]:
        art = ", ".join(_ev_link(a) for a in r["artifacts"][:3]) or "—"
        out.append(f"| {r['id']}: {_md_cell(r['title'])} | {r['phase']} | {'yes' if r['critical'] else ''} | "
                   f"{r['evidence_class']} | {_md_cell(r['result'])} | {_md_cell(r['reason'])} | {art} |")

    out += ["", "## 3. Findings", ""]
    if not ctx["findings"]:
        out.append("No findings were recorded. Read this together with the coverage matrix: unchecked areas are listed there as NOT-TESTED.")
    for f in ctx["findings"]:
        loc = f.get("location") or {}
        where = loc.get("endpoint") or (f"{loc['file']}:{loc['line']}" if loc.get("file") and loc.get("line") else loc.get("file") or "—")
        out += [f"### {f['id']} · {f.get('severity', '').upper()} · {f['evidence_class']} — {_md_cell(f['title'])}", "",
                f"- **Location:** `{_md_cell(where)}`",
                f"- **Status:** {f.get('status', 'open')}" + (f" · waiver {f['waiver_id']}" if f.get("waiver_id") else "")]
        if f.get("impact"):
            out.append(f"- **What this means:** {f['impact']}")
        if f.get("repro"):
            out.append(f"- **Reproduce:** {f['repro']}")
        if f.get("fix"):
            out.append(f"- **Suggested fix:** {f['fix']}")
        rt = (f.get("retest") or {}).get("status", "not-run")
        out.append(f"- **Retest:** {rt}")
        if f.get("evidence"):
            out.append("- **Evidence:** " + ", ".join(_ev_link(ev["path"]) for ev in f["evidence"]))
        if f.get("tool"):
            t = f["tool"]
            name = " ".join(x for x in (t.get("name", "?"), t.get("version")) if x)
            out.append(f"- **Reported by:** {name}, rule `{_md_cell(t.get('rule_id', ''))}` (scope: {_md_cell(t.get('scope', 'unknown'))})")
        if f.get("not_tested_reason"):
            out.append(f"- **Why not reproduced:** {f['not_tested_reason']}")
        out.append("")

    out += ["## 4. Adversarial verification", ""]
    if not ctx["adversarial"]:
        out.append("No entries required adversarial verification in this run.")
    else:
        out += ["| Entry | Claim | Outcome | Action |", "|---|---|---|---|"]
        for e in ctx["adversarial"]:
            a = e["adversarial"]
            out.append(f"| {e['id']} | {_md_cell(e['title'])} | {a.get('outcome', 'not-run')} | {_md_cell(a.get('action_taken') or a.get('summary', ''))} |")
    out.append("")

    out += _md_privacy(ctx)
    out += _md_documents(ctx)
    out += _md_perf(ctx)
    out += _md_trend(ctx)
    out += _md_waivers(ctx)

    out += ["## 10. Limitations", ""] + [f"- {x}" for x in LIMITATIONS]
    nt = [r for r in ctx["coverage"] if r["evidence_class"] == "NOT-TESTED" and r["applicable"]]
    if nt:
        out += ["", f"{len(nt)} applicable checks were NOT-TESTED in this run (see coverage matrix)."]
    out.append("")

    out += ["## Disclaimer", "", DISCLAIMER, ""]

    if ctx["false_positives"]:
        out += ["## Appendix A. Findings judged false positives", "",
                "| Entry | Title | Reason | Verified at |", "|---|---|---|---|"]
        for e in ctx["false_positives"]:
            ver = e.get("verification") or {}
            out.append(f"| {e['id']} | {_md_cell(e['title'])} | {_md_cell(ver.get('reason', 'no reason recorded'))} | {_md_cell(ver.get('code_ref', '—'))} |")
        out.append("")
    return "\n".join(out)


def _md_privacy(ctx: dict) -> list[str]:
    out = ["## 5. Privacy summary", ""]
    inv = ctx["inventory"]
    if not inv:
        out += ["No data inventory recorded (phase 1 not run).", ""]
    else:
        out += [f"Inventory confirmed by user: {'yes' if inv.get('confirmed_by_user') else 'no'}", "",
                "| Field | Class | Used in code | Encrypted at rest | Retention | Source |", "|---|---|---|---|---|---|"]
        for fld in inv.get("fields", []):
            pv = fld.get("provenance", {})
            src = pv.get("source", "?") + (f" ({', '.join(pv.get('refs', [])[:2])})" if pv.get("refs") else "")
            used = {True: "yes", False: "no"}.get(fld.get("used_in_code"), "unknown")
            out.append(f"| {_md_cell(fld['name'])} | {fld['classification']} | {used} | {fld.get('encrypted_at_rest', 'unknown')} | "
                       f"{_md_cell(fld.get('retention', 'none defined'))} | {_md_cell(src)} |")
        tps = inv.get("third_parties", [])
        out += ["", f"Third parties contacted by the code: {len(tps)}", ""]
        if tps:
            out += ["| Host | Vendor | Role | Data sent | Purpose |", "|---|---|---|---|---|"]
            for t in tps:
                out.append(f"| {_md_cell(t['host'])} | {_md_cell(t.get('vendor', '?'))} | {t.get('role', 'unknown')} | "
                           f"{_md_cell(', '.join(t.get('data_sent', [])))} | {_md_cell(t.get('purpose', ''))} |")
        out.append("")
    if ctx["regimes"]:
        out += ["Applicable regimes (from the skill's dated reference data; verify against the official source):", "",
                "| Regime | Applies | Why | Reference last verified |", "|---|---|---|---|"]
        for r in ctx["regimes"]:
            stale = " (possibly stale)" if r["stale"] else ""
            out.append(f"| {_md_cell(r.get('name'))} | {'yes' if r.get('applies') else 'no'} | {_md_cell(r.get('why', ''))} | {r.get('last_verified', 'unknown')}{stale} |")
        out.append("")
    rights = ctx["privacy"].get("rights_tests") or []
    if rights:
        out += ["Data-subject rights, executed for a test user:", "", "| Right | Result | Evidence class | Evidence |", "|---|---|---|---|"]
        for r in rights:
            ev = _ev_link(r["evidence"]) if r.get("evidence") else "—"
            out.append(f"| {_md_cell(r.get('right'))} | {_md_cell(r.get('result'))} | {r.get('evidence_class', 'NOT-TESTED')} | {ev} |")
        out.append("")
    ca = ctx["privacy"].get("cookie_audit")
    if ca:
        out += ["Cookie and tracker audit:", ""]
        for stage in ("before_consent", "after_reject", "after_accept"):
            items = ca.get(stage)
            if items is not None:
                out.append(f"- {stage.replace('_', ' ')}: {len(items)} non-essential cookies/trackers" + (f" ({_md_cell(', '.join(items[:8]))})" if items else ""))
        if ca.get("evidence"):
            out.append(f"- evidence: {_ev_link(ca['evidence'])}")
        out.append("")
    mism = [f for f in ctx["findings"] if f.get("category") == "policy-mismatch"]
    out += [f"Policy-consistency mismatches: {len(mism)}" + (f" ({', '.join(f['id'] for f in mism)})" if mism else ""), ""]
    return out


def _md_documents(ctx: dict) -> list[str]:
    docs = ctx["documents"]
    out = ["## 6. Generated documents", ""]
    if not docs.get("documents"):
        out.append("No documents generated in this run.")
    else:
        out.append("All documents are DRAFTS, not legal advice. Have a qualified lawyer review them before publishing.")
        out.append("")
        for d in docs["documents"]:
            out.append(f"- {_md_cell(d.get('name'))}: `{_md_cell(d.get('path'))}`" + (f" — {_md_cell(d['applies_reason'])}" if d.get("applies_reason") else ""))
    qs = docs.get("lawyer_questions") or []
    out += ["", "### Questions for a lawyer", ""]
    out += [f"{i}. {_md_cell(q)}" for i, q in enumerate(qs, 1)] or ["None recorded in this run."]
    out.append("")
    return out


def _md_perf(ctx: dict) -> list[str]:
    perf = ctx["perf"]
    out = ["## 7. Performance", ""]
    profs = perf.get("profiles") or []
    if not profs:
        return out + ["Not run: no load-test results recorded.", ""]
    out += ["| Profile | Target RPS | Achieved RPS | p50 ms | p95 ms | p99 ms | Error rate |", "|---|---|---|---|---|---|---|"]
    for p in profs:
        out.append(f"| {_md_cell(p.get('name'))} | {p.get('target_rps', '—')} | {p.get('rps', '—')} | {p.get('p50_ms', '—')} | "
                   f"{p.get('p95_ms', '—')} | {p.get('p99_ms', '—')} | {p.get('error_rate', '—')} |")
    for k in ("breaking_point", "first_failure", "traffic_source", "hardware_note"):
        if perf.get(k):
            out.append(f"\n- {k.replace('_', ' ')}: {_md_cell(perf[k])}")
    out.append("")
    return out


def _md_trend(ctx: dict) -> list[str]:
    t = ctx["trend"]
    out = ["## 8. Trend vs previous run", ""]
    if not t["previous_run"]:
        return out + ["No previous run in history; everything open is new.", ""]
    out += [f"Previous run: {t['previous_run']}", "",
            f"- New: {len(t['new'])}", f"- Fixed: {len(t['fixed'])}", f"- Regressions (fixed before, open again): {len(t['regressions'])}", ""]
    return out


def _md_waivers(ctx: dict) -> list[str]:
    out = ["## 9. Waivers", ""]
    if not ctx["waivers_active"] and not ctx["waivers_expired"]:
        return out + ["No waivers recorded.", ""]
    out += ["| Waiver | Covers | Reason | Owner | Expires | State |", "|---|---|---|---|---|---|"]
    for state, ws in (("active", ctx["waivers_active"]), ("EXPIRED (not honored)", ctx["waivers_expired"])):
        for w in ws:
            cov = w["match"].get("finding_id") or w["match"].get("fingerprint", "")[:12]
            out.append(f"| {w['id']} | {_md_cell(cov)} | {_md_cell(w['reason'])} | {_md_cell(w['owner'])} | {w['expires']} | {state} |")
    out.append("")
    return out


