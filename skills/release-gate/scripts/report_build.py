def _inline(text: str) -> str:
    """Escape text, then re-enable the tiny Markdown subset render_md emits."""
    esc = html.escape(text, quote=True)

    def link(m: re.Match) -> str:
        label, href = m.group(1), html.unescape(m.group(2))
        if _SAFE_LINK.match(href):
            return f'<a href="{html.escape(href, quote=True)}">{label}</a>'
        return label  # never emit unexpected hrefs (javascript:, http:, …)

    esc = _MD_LINK.sub(link, esc)
    esc = _MD_CODE.sub(lambda m: f"<code>{m.group(1)}</code>", esc)
    esc = _MD_BOLD.sub(lambda m: f"<strong>{m.group(1)}</strong>", esc)
    esc = re.sub(r"\b(EXPLOITED|TOOL-CONFIRMED|SUSPECTED|VERIFIED-ABSENT|NOT-TESTED)\b", r'<span class="ec ec-\1">\1</span>', esc)
    return esc


def _md_to_html(md: str) -> str:
    """Render the Markdown produced by render_md. Not a general Markdown parser."""
    lines, out, i = md.split("\n"), [], 0
    in_list = None
    while i < len(lines):
        ln = lines[i]
        if ln.startswith("|") and i + 1 < len(lines) and re.match(r"^\|[-| ]+\|$", lines[i + 1]):
            head = _split_row(ln)
            i += 2
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                rows.append(_split_row(lines[i]))
                i += 1
            out.append('<div class="tablewrap"><table><thead><tr>' + "".join(f"<th>{_inline(h)}</th>" for h in head) + "</tr></thead><tbody>")
            out += ["<tr>" + "".join(f"<td>{_inline(c)}</td>" for c in r) + "</tr>" for r in rows]
            out.append("</tbody></table></div>")
            continue
        m_ul, m_ol = re.match(r"^- (.*)", ln), re.match(r"^\d+\. (.*)", ln)
        kind = "ul" if m_ul else "ol" if m_ol else None
        if in_list and kind != in_list:
            out.append(f"</{in_list}>")
            in_list = None
        if kind:
            if not in_list:
                out.append(f"<{kind}>")
                in_list = kind
            out.append(f"<li>{_inline((m_ul or m_ol).group(1))}</li>")
        elif ln.startswith("### "):
            out.append(f"<h3>{_inline(ln[4:])}</h3>")
        elif ln.startswith("## "):
            out.append(f"<h2>{_inline(ln[3:])}</h2>")
        elif ln.startswith("# "):
            out.append(f"<h1>{_inline(ln[2:])}</h1>")
        elif ln.strip():
            out.append(f"<p>{_inline(ln)}</p>")
        i += 1
    if in_list:
        out.append(f"</{in_list}>")
    return "\n".join(out)


def _split_row(row: str) -> list[str]:
    cells = re.split(r"(?<!\\)\|", row.strip()[1:-1])
    return [c.strip().replace("\\|", "|") for c in cells]


def svg_severity_bars(counts: dict) -> str:
    colors = {"critical": "#b42318", "high": "#d92d20", "medium": "#b54708", "low": "#6b6a65", "info": "#98a2b3"}
    mx = max(counts.values()) or 1
    w, bar_h, gap = 420, 18, 8
    parts = [f'<svg role="img" aria-label="Open findings by severity" viewBox="0 0 {w} {5 * (bar_h + gap)}" width="100%" style="max-width:{w}px">']
    for i, sev in enumerate(rglib.SEVERITIES):
        y = i * (bar_h + gap)
        bw = int((w - 140) * counts[sev] / mx)
        parts.append(f'<text x="0" y="{y + 13}">{sev}</text><rect x="70" y="{y}" width="{max(bw, 1)}" height="{bar_h}" rx="3" fill="{colors[sev]}"/>'
                     f'<text x="{76 + bw}" y="{y + 13}">{counts[sev]}</text>')
    parts.append("</svg>")
    return "".join(parts)


def svg_latency(perf: dict) -> str:
    profs = [p for p in perf.get("profiles") or [] if isinstance(p.get("p95_ms"), (int, float))]
    if not profs:
        return ""
    mx = max(max(p.get(k) or 0 for k in ("p50_ms", "p95_ms", "p99_ms")) for p in profs) or 1
    gw, h = 90, 160
    w = 40 + gw * len(profs)
    parts = [f'<svg role="img" aria-label="Latency by load profile" viewBox="0 0 {w} {h + 30}" width="100%" style="max-width:{w}px">']
    for i, p in enumerate(profs):
        for j, (k, col) in enumerate((("p50_ms", "#067647"), ("p95_ms", "#b54708"), ("p99_ms", "#b42318"))):
            val = p.get(k) or 0
            bh = int(h * val / mx)
            x = 40 + i * gw + j * 22
            parts.append(f'<rect x="{x}" y="{h - bh}" width="18" height="{bh}" fill="{col}"><title>{html.escape(str(p.get("name")))} {k} {val}</title></rect>')
        parts.append(f'<text x="{40 + i * gw}" y="{h + 16}">{html.escape(str(p.get("name"))[:12])}</text>')
    parts.append(f'<text x="0" y="12">{int(mx)} ms</text><text x="0" y="{h}">0</text></svg>')
    return "".join(parts)


def render_html(ctx: dict, md: str) -> str:
    v = ctx["verdict"]["verdict"]
    body = _md_to_html(md)
    badge = f'<p><span class="verdict v-{v.replace(" ", "-")}">{html.escape(v)}</span></p>'
    body = body.replace("</h2>", "</h2>" + badge, 1)
    charts = f'<h3>Open findings by severity</h3>{svg_severity_bars(ctx["counts"])}'
    body = body.replace("<h2>2. Coverage matrix</h2>", charts + "\n<h2>2. Coverage matrix</h2>", 1)
    lat = svg_latency(ctx["perf"])
    if lat:
        body = body.replace("<h2>7. Performance</h2>", "<h2>7. Performance</h2>" + lat, 1)
    title = html.escape(f"release-gate: {ctx['product']} {ctx['date']}")
    return (f'<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
            f'<meta http-equiv="Content-Security-Policy" content="default-src \'none\'; style-src \'unsafe-inline\'; img-src data:">'
            f"<title>{title}</title><style>{CSS}</style></head><body><main>{body}</main></body></html>\n")


