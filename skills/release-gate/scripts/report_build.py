SARIF_LEVEL = {"critical": "error", "high": "error", "medium": "warning", "low": "note", "info": "note"}


def render_sarif(ctx: dict) -> dict:
    rules, results = {}, []
    for f in ctx["findings"]:
        rid = (f.get("tool") or {}).get("rule_id") or f.get("check_id") or f["category"]
        rules.setdefault(rid, {"id": rid, "name": re.sub(r"[^A-Za-z0-9]", "", rid.title())[:60] or "Rule",
                               "shortDescription": {"text": f["title"][:200]}})
        res = {"ruleId": rid, "level": SARIF_LEVEL.get(f.get("severity"), "note"),
               "message": {"text": f"{f['title']} [{f['evidence_class']}]"},
               "properties": {"release-gate-id": f["id"], "severity": f.get("severity"), "evidence_class": f["evidence_class"],
                              "status": f.get("status", "open"), "check_id": f.get("check_id")}}
        loc = f.get("location") or {}
        if loc.get("file"):
            region = {"startLine": max(int(loc.get("line") or 1), 1)}
            res["locations"] = [{"physicalLocation": {"artifactLocation": {"uri": loc["file"]}, "region": region}}]
        if f.get("fingerprint"):
            res["partialFingerprints"] = {"releaseGate/v1": f["fingerprint"]}
        results.append(res)
    return {"$schema": "https://json.schemastore.org/sarif-2.1.0.json", "version": "2.1.0",
            "runs": [{"tool": {"driver": {"name": "release-gate", "informationUri": "https://github.com/Jenari-Dev/release-gate",
                                          "rules": list(rules.values())}}, "results": results}]}


def render_json(ctx: dict) -> dict:
    keep = ("product", "date", "mode", "generated_at", "verdict", "counts", "coverage", "trend", "regimes")
    out = {k: ctx[k] for k in keep}
    out["entries"] = ctx["entries"]
    out["waivers"] = {"active": ctx["waivers_active"], "expired": ctx["waivers_expired"]}
    out["documents"] = ctx["documents"]
    out["perf"] = ctx["perf"]
    out["limitations"] = LIMITATIONS
    out["disclaimer"] = DISCLAIMER
    return out


# --------------------------------------------------------------------------- main

def build(project: Path, mode: str, date: str | None = None, extra_findings: list[Path] | None = None,
          write_history: bool = True) -> tuple[int, dict]:
    import report_lint  # local import keeps module import cheap for tests

    state = load_state(project, extra_findings or [])
    date = date or rglib.today().isoformat()
    ctx = build_context(state, load_catalog(), mode, date)
    md = render_md(ctx)
    outputs = {"md": md, "html": render_html(ctx, md),
               "sarif": json.dumps(render_sarif(ctx), indent=2) + "\n",
               "json": json.dumps(render_json(ctx), indent=2, default=str) + "\n"}
    rdir = state["state_dir"] / "reports"
    base = rdir / f"release-gate-{date}"
    paths = {}
    for ext, text in outputs.items():
        p = base.with_suffix(f".{ext}")
        p.write_text(text, encoding="utf-8")
        paths[ext] = p
    problems = report_lint.lint_paths(list(paths.values()), state["state_dir"])
    if problems:
        failed = {}
        for ext, p in paths.items():
            fp = rdir / f"release-gate-{date}.lint-failed.{ext}"
            p.replace(fp)
            failed[ext] = fp
        return 2, {"paths": failed, "problems": problems, "verdict": ctx["verdict"]}
    if write_history:
        rglib.dump_data(state["state_dir"] / "history" / f"{rglib.stamp()}.json", history_summary(ctx["entries"], ctx["verdict"], mode))
    return 0, {"paths": paths, "problems": [], "verdict": ctx["verdict"]}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--project", required=True, type=Path)
    ap.add_argument("--mode", choices=MODES, default="full")
    ap.add_argument("--date", help="report date (default: today, UTC)")
    ap.add_argument("--findings", type=Path, action="append", default=[], help="extra findings files")
    ap.add_argument("--no-history", action="store_true")
    args = ap.parse_args(argv)
    code, res = build(args.project, args.mode, args.date, args.findings, not args.no_history)
    print(f"verdict: {res['verdict']['verdict']}")
    for ext, p in res["paths"].items():
        print(f"{ext}: {p}")
    for prob in res["problems"]:
        print(f"LINT: {prob}", file=sys.stderr)
    return code


if __name__ == "__main__":
    sys.exit(main())
